import React from "react";
import { describe, expect, it, vi } from "vitest";
import { render, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { http, HttpResponse } from "msw";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { server } from "@/test/server";
import { SchoolSessionContext } from "@/context/providers/SchoolSessionProvider";
import AddRemarks from "./AddRemarks";

vi.mock("../dialog/CustomDialogTitle", () => ({ default: ({ title }) => <h2>{title}</h2> }));

const base = "http://api.test/api/frebbys/v1";

function setup(remark) {
  const dispatch = vi.fn();
  const setOpen = vi.fn();
  const user = userEvent.setup();
  render(
    <QueryClientProvider client={new QueryClient({ defaultOptions: { mutations: { retry: false } } })}>
      <SchoolSessionContext.Provider value={{ schoolSessionDispatch: dispatch }}>
        <AddRemarks open setOpen={setOpen} id="exam1" remark={remark} />
      </SchoolSessionContext.Provider>
    </QueryClientProvider>
  );
  return { user, dispatch, setOpen };
}

describe("remarks dialog", () => {
  it("sends the comment the teacher typed, not only suggestions they picked", async () => {
    let body;
    server.use(
      http.put(`${base}/examinations/comments`, async ({ request }) => {
        body = await request.json();
        return HttpResponse.json("Remarks updated successfully!!!", { status: 201 });
      })
    );
    const { user, setOpen } = setup({});
    await user.click(screen.getByLabelText("Class Teacher's Comments"));
    await user.paste("A kind and diligent pupil.");
    await user.click(screen.getByRole("button", { name: "Save Changes" }));
    await waitFor(() => expect(setOpen).toHaveBeenCalledWith(false));
    expect(body._id).toBe("exam1");
    expect(body.comments.teachersComments).toBe("A kind and diligent pupil.");
    expect(body.comments.conduct).toBe("");
  });

  it("shows existing remarks and tells the teacher when they were written automatically", () => {
    setup({ teachersComments: "Quite impressive, keep it up.", autoGenerated: true });
    expect(screen.getByLabelText("Class Teacher's Comments")).toHaveValue("Quite impressive, keep it up.");
    expect(screen.getByText(/written automatically/i)).toBeInTheDocument();
  });

  it("does not show the automatic notice for hand-written remarks", () => {
    setup({ teachersComments: "Mine.", autoGenerated: false });
    expect(screen.queryByText(/written automatically/i)).not.toBeInTheDocument();
  });

  it("keeps the dialog open when saving fails", async () => {
    server.use(http.put(`${base}/examinations/comments`, () => HttpResponse.json("Error saving remarks.Try again later!!!", { status: 400 })));
    const { user, setOpen, dispatch } = setup({});
    await user.type(screen.getByLabelText("Interest"), "Reading");
    await user.click(screen.getByRole("button", { name: "Save Changes" }));
    await waitFor(() => expect(dispatch).toHaveBeenCalled());
    expect(setOpen).not.toHaveBeenCalled();
  });
});
