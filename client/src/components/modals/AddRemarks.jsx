import React, { useContext, useEffect } from "react";
import Alert from "@mui/material/Alert";
import Button from "@mui/material/Button";
import Autocomplete from "@mui/material/Autocomplete";
import Dialog from "@mui/material/Dialog";
import DialogActions from "@mui/material/DialogActions";
import DialogContent from "@mui/material/DialogContent";
import Stack from "@mui/material/Stack";
import TextField from "@mui/material/TextField";
import { useMutation, useQueryClient } from "@tanstack/react-query";
import { Controller, useForm } from "react-hook-form";
import { postExamsRemarks } from "@/api/ExaminationAPI";
import { CONDUCT, INTEREST, TEACHERSREMARKS } from "@/config/remarks";
import { alertError, alertSuccess } from "@/context/actions/globalAlertActions";
import { SchoolSessionContext } from "@/context/providers/SchoolSessionProvider";
import CustomDialogTitle from "../dialog/CustomDialogTitle";

// The server keeps at most 1000 characters of each remark.
export const REMARK_MAX_LENGTH = 1000;

const FIELDS = [
  { name: "conduct", label: "Conduct/Attitude", options: CONDUCT },
  { name: "interest", label: "Interest", options: INTEREST },
  { name: "teachersComments", label: "Class Teacher's Comments", options: TEACHERSREMARKS },
  { name: "headteachersComments", label: "Headteacher's Comments", options: TEACHERSREMARKS },
];

const valuesFrom = (remark) =>
  Object.fromEntries(FIELDS.map(({ name }) => [name, remark?.[name] ?? ""]));

function AddRemarks({ open, setOpen, id, remark }) {
  const { schoolSessionDispatch } = useContext(SchoolSessionContext);
  const queryClient = useQueryClient();

  const handleCloseDialog = () => setOpen(false);

  const { mutate, isPending } = useMutation({
    mutationFn: postExamsRemarks,
  });

  const { control, handleSubmit, reset } = useForm({ defaultValues: valuesFrom(remark) });

  // After the results are refreshed the dialog shows the latest remarks. Compared by content,
  // so a new-but-equal object from the parent does not wipe what is being typed.
  const saved = JSON.stringify(valuesFrom(remark));
  useEffect(() => {
    reset(JSON.parse(saved));
  }, [saved, reset]);

  const onSubmit = (values) => {
    mutate(
      { _id: id, comments: values },
      {
        onSettled: () => {
          queryClient.invalidateQueries({ queryKey: ["exams-id", id] });
          queryClient.invalidateQueries({ queryKey: ["exams-reports"] });
        },
        onSuccess: (data) => {
          schoolSessionDispatch(alertSuccess(data));
          handleCloseDialog();
        },
        onError: (error) => {
          schoolSessionDispatch(alertError(error));
        },
      }
    );
  };

  return (
    <Dialog open={open} onClose={handleCloseDialog} maxWidth="sm" fullWidth className="add-remark">
      <CustomDialogTitle title="Add Remarks" onClose={handleCloseDialog} />
      <DialogContent sx={{ p: 1 }}>
        <Stack spacing={2} py={2}>
          {remark?.autoGenerated && (
            <Alert severity="info">
              These remarks were written automatically from the student&apos;s total score. Saving replaces
              them with what is shown here, so edit them first if you want your own words.
            </Alert>
          )}
          {FIELDS.map(({ name, label, options }) => (
            // freeSolo: the person may pick a suggestion or type their own. The typed text is
            // read from the input box (onInputChange); onChange alone only fires for picks.
            <Controller
              key={name}
              name={name}
              control={control}
              render={({ field }) => (
                <Autocomplete
                  freeSolo
                  options={options}
                  inputValue={field.value ?? ""}
                  onInputChange={(_, value) => field.onChange(value)}
                  renderInput={(params) => (
                    <TextField
                      {...params}
                      label={label}
                      size="small"
                      slotProps={{ htmlInput: { ...params.inputProps, maxLength: REMARK_MAX_LENGTH } }}
                    />
                  )}
                />
              )}
            />
          ))}
        </Stack>
      </DialogContent>
      <DialogActions sx={{ padding: 2 }}>
        <Button variant="contained" disabled={isPending} onClick={handleSubmit(onSubmit)}>
          {isPending ? "Saving..." : "Save Changes"}
        </Button>
      </DialogActions>
    </Dialog>
  );
}

export default AddRemarks;
