const request = require("supertest");
const mongoose = require("mongoose");

const app = require("../app");
const Session = require("../models/sessionModel");
const Term = require("../models/termModel");
const Level = require("../models/levelModel");
const Student = require("../models/studentModel");
const Examination = require("../models/examinationModel");
const Attendance = require("../models/attendanceModel");
const { createSchool, createUser, staffToken } = require("./helpers");

const base = "/api/frebbys/v1";
const oid = () => new mongoose.Types.ObjectId();
const as = (req, token) => req.set("Authorization", `Bearer ${token}`);
const make = (Model, data) => new Model(data).save({ validateBeforeSave: false });
const uniq = (p) => `${p}${oid().toString().slice(-10)}`;

describe("exam scores and attendance correctness (Stage 9)", () => {
  let school, admin, adminTok, session, term, level, s1, s2, exam1, exam2;
  const maths = String(oid());
  const english = String(oid());

  beforeAll(async () => {
    school = await createSchool();
    admin = await createUser(school, "administrator");
    adminTok = staffToken(admin);
    session = await make(Session, { school: school._id });
    term = await make(Term, { school: school._id, session: session._id, active: true, status: "current", exams: { scorePreference: "40/60" } });
    s1 = await make(Student, { indexnumber: uniq("e"), school: school._id, firstname: "Ama", surname: "Mensah", gender: "female" });
    s2 = await make(Student, { indexnumber: uniq("e"), school: school._id, firstname: "Kofi", surname: "Boateng", gender: "male" });
    level = await make(Level, { school: school._id, session: session._id, term: term._id, students: [s1._id, s2._id] });
    exam1 = await make(Examination, { session: session._id, term: term._id, level: level._id, student: s1._id, school: school._id, createdBy: admin._id, scores: [] });
    exam2 = await make(Examination, { session: session._id, term: term._id, level: level._id, student: s2._id, school: school._id, createdBy: admin._id, scores: [] });
  });

  const post = (body, path = "") => as(request(app).post(`${base}/examinations${path}`), adminTok).send(body);
  const reload = (id) => Examination.findById(id);

  describe("saving scores", () => {
    it("computes the total and overall score itself", async () => {
      const res = await post({ examsId: String(exam1._id), scores: [{ _id: maths, subject: "Maths", classScore: "30", examsScore: 45, totalScore: 9999 }] });
      expect(res.status).toBe(201);
      const saved = await reload(exam1._id);
      expect(saved.scores[0].totalScore).toBe(75);
      expect(saved.overallScore).toBe(75);
    });

    it("rejects a score above its share of the term split, and saves nothing", async () => {
      const before = await reload(exam1._id);
      const res = await post({ examsId: String(exam1._id), scores: [{ _id: english, subject: "English", classScore: 41, examsScore: 10 }] });
      expect(res.status).toBe(400);
      expect(res.body).toMatch(/between 0 and 40/);
      expect((await reload(exam1._id)).scores).toHaveLength(before.scores.length);
    });

    it("does not replace hand-written comments when scores are saved again", async () => {
      const put = await as(request(app).put(`${base}/examinations/comments`), adminTok).send({ _id: String(exam1._id), comments: { teachersComments: "Keep this", conduct: "Polite" } });
      expect(put.status).toBe(201);
      await post({ examsId: String(exam1._id), scores: [{ _id: english, subject: "English", classScore: 20, examsScore: 30 }] });
      const saved = await reload(exam1._id);
      expect(saved.comments.teachersComments).toBe("Keep this");
      expect(saved.scores).toHaveLength(2);
      expect(saved.overallScore).toBe(125);
    });

    it("generates remarks only until someone writes their own", async () => {
      await post({ examsId: String(exam2._id), scores: [{ _id: maths, subject: "Maths", classScore: 10, examsScore: 10 }] });
      const first = await reload(exam2._id);
      expect(first.comments.autoGenerated).toBe(true);
      expect(first.comments.teachersComments).toBeTruthy();
    });

    it("rejects invalid comments", async () => {
      for (const comments of ["text", null, { a: { b: 1 } }]) {
        expect((await as(request(app).put(`${base}/examinations/comments`), adminTok).send({ _id: String(exam1._id), comments })).status).toBe(400);
      }
    });

    it("keeps both teachers' changes when two save the same student at once", async () => {
      const fresh = await make(Examination, { session: session._id, term: term._id, level: level._id, student: oid(), school: school._id, createdBy: admin._id, scores: [] });
      const subjects = ["A", "B", "C", "D"].map((name) => ({ _id: String(oid()), subject: name, classScore: 10, examsScore: 10 }));
      const results = await Promise.all(subjects.map((score) => post({ examsId: String(fresh._id), scores: [score] })));
      expect(results.every((r) => r.status === 201)).toBe(true);
      const saved = await reload(fresh._id);
      expect(saved.scores.map((s) => s.subject).sort()).toEqual(["A", "B", "C", "D"]);
      expect(saved.overallScore).toBe(80);
    });
  });

  describe("replacing scores (update)", () => {
    it("validates, recomputes totals and still removes omitted subjects", async () => {
      const bad = await post({ session: { examsId: String(exam1._id) }, scores: [{ _id: maths, subject: "Maths", classScore: 99, examsScore: 0 }] }, "/update");
      expect(bad.status).toBe(400);
      const noId = await post({ session: { examsId: String(exam1._id) }, scores: [{ subject: "Maths", classScore: 1, examsScore: 1 }] }, "/update");
      expect(noId.status).toBe(400);

      const ok = await post({ session: { examsId: String(exam1._id) }, scores: [{ _id: maths, subject: "Maths", classScore: 35, examsScore: 55, totalScore: 1 }] }, "/update");
      expect(ok.status).toBe(201);
      const saved = await reload(exam1._id);
      expect(saved.scores).toHaveLength(1);
      expect(saved.scores[0].totalScore).toBe(90);
      expect(saved.overallScore).toBe(90);
      expect(saved.comments.teachersComments).toBe("Keep this");
    });
  });

  describe("bulk upload", () => {
    const bulk = (results) => post({ session: String(session._id), term: String(term._id), level: String(level._id), results }, "/bulk");

    it("matches students by index number ignoring case, and skips unknown students without writing blanks", async () => {
      const res = await bulk([
        { _id: maths, subject: "Maths", indexnumber: s2.indexnumber.toUpperCase(), classScore: 30, examsScore: 40 },
        { _id: maths, subject: "Maths", indexnumber: "nobody", classScore: 1, examsScore: 1 },
      ]);
      expect(res.status).toBe(200);
      const saved = await reload(exam2._id);
      expect(saved.scores.find((s) => s.subject === "Maths").totalScore).toBe(70);
      expect(saved.scores.every((s) => s.subject)).toBe(true);
      // the other student in the class was not touched by a row that is not theirs
      expect((await reload(exam1._id)).scores.map((s) => s.subject)).toEqual(["Maths"]);
    });

    it("rejects the whole upload when one row is invalid", async () => {
      const before = (await reload(exam2._id)).overallScore;
      const res = await bulk([
        { _id: maths, subject: "Maths", indexnumber: s2.indexnumber, classScore: 10, examsScore: 10 },
        { _id: maths, subject: "Maths", indexnumber: s1.indexnumber, classScore: "x", examsScore: 10 },
      ]);
      expect(res.status).toBe(400);
      expect(res.body).toMatch(/Row 2/);
      expect((await reload(exam2._id)).overallScore).toBe(before);
    });

    it("refuses a term of another school", async () => {
      const other = await createSchool();
      const foreignTerm = await make(Term, { school: other._id });
      const res = await post({ session: String(session._id), term: String(foreignTerm._id), level: String(level._id), results: [{ _id: maths, subject: "Maths", indexnumber: "x", classScore: 1 }] }, "/bulk");
      expect(res.status).toBe(403);
    });
  });

  describe("creating a student's exam record on first view", () => {
    it("works (createdBy is now set)", async () => {
      const s3 = await make(Student, { indexnumber: uniq("e"), school: school._id, firstname: "Yaw" });
      const res = await post({ session: String(session._id), term: String(term._id), level: String(level._id), student: String(s3._id) }, "/student/academics");
      expect(res.status).toBe(200);
      const created = await Examination.findOne({ student: s3._id });
      expect(created).toBeTruthy();
      expect(String(created.createdBy)).toBe(String(admin._id));
    });
  });

  describe("attendance", () => {
    const day = "2026-10-13"; // a Tuesday
    const get = (date = day) =>
      as(request(app).get(`${base}/attendances/${level._id}?date=${date}&term=${term._id}&session=${session._id}`), adminTok);
    const save = (path, body) =>
      as(request(app).post(`${base}/attendances${path}`), adminTok).send({ level: String(level._id), term: String(term._id), session: String(session._id), ...body });
    const registers = (d = day) => Attendance.find({ level: level._id, date: { $gte: new Date(`${d}T00:00:00Z`), $lt: new Date(`${d}T23:59:59Z`) } });

    it("rejects a missing or invalid date", async () => {
      expect((await get("not-a-date")).status).toBe(400);
      expect((await save("", { date: "", status: [] })).status).toBe(400);
    });

    it("opens one blank register per day however the date is written", async () => {
      expect((await get(day)).status).toBe(200);
      expect((await get(`${day}T10:30:00.000Z`)).status).toBe(200);
      expect(await registers()).toHaveLength(1);
    });

    it("saves into that same register from both write routes (no duplicates)", async () => {
      const a = await save("", { date: day, status: [{ _id: String(s1._id), status: "Present" }, { _id: String(s2._id), status: "Absent" }] });
      expect(a.status).toBe(201);
      const b = await save("/student", { date: `${day}T08:00:00.000Z`, status: [{ _id: String(s2._id), status: "Present" }] });
      expect(b.status).toBe(201);

      const found = await registers();
      expect(found).toHaveLength(1);
      expect(found[0].active).toBe(true);
      const byId = Object.fromEntries(found[0].status.map((e) => [String(e._id), e.status]));
      expect(byId[String(s1._id)]).toBe("Present"); // kept by the per-student merge
      expect(byId[String(s2._id)]).toBe("Present"); // updated
    });

    it("takes names from the class, not from the request, and refuses outsiders", async () => {
      const res = await save("", { date: "2026-10-14", status: [{ _id: String(s1._id), status: "Present", fullName: "FORGED" }] });
      expect(res.status).toBe(201);
      const [reg] = await registers("2026-10-14");
      expect(reg.status[0].fullName).not.toBe("FORGED");

      const stranger = await make(Student, { indexnumber: uniq("e"), school: school._id, firstname: "Out" });
      expect((await save("", { date: "2026-10-15", status: [{ _id: String(stranger._id), status: "Present" }] })).status).toBe(400);
      expect(await registers("2026-10-15")).toHaveLength(0);
      expect((await save("", { date: "2026-10-15", status: [{ _id: String(s1._id), status: "x".repeat(50) }] })).status).toBe(400);
    });

    it("refuses future dates and terms or sessions of another school", async () => {
      const future = new Date(Date.now() + 5 * 86400000).toISOString();
      expect((await save("", { date: future, status: [] })).status).toBe(400);

      const other = await createSchool();
      const foreignTerm = await make(Term, { school: other._id });
      expect((await save("", { date: day, term: String(foreignTerm._id), status: [] })).status).toBe(403);
    });

    it("does not create a register for a weekend", async () => {
      const res = await get("2026-10-17"); // Saturday
      expect(res.status).toBe(200);
      expect(res.body.status).toEqual([]);
      expect(await registers("2026-10-17")).toHaveLength(0);
    });
  });
});
