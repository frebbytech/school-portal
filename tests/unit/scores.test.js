const {
  scorePreferences, cleanScore, cleanScores, mergeBy, overallOf, nextComments, cleanComments,
} = require("../../common/scores");

const prefs = { class: 50, exams: 50 };

describe("score rules", () => {
  it("reads the term's score split and falls back to 100/100", () => {
    expect(scorePreferences({ exams: { scorePreference: "30/70" } })).toEqual({ class: 30, exams: 70 });
    for (const bad of [undefined, {}, { exams: {} }, { exams: { scorePreference: "abc" } }, { exams: { scorePreference: "0/100" } }]) {
      expect(scorePreferences(bad)).toEqual({ class: 100, exams: 100 });
    }
  });

  it("computes the total itself and ignores a client total", () => {
    const { score } = cleanScore({ subject: "Maths", _id: 5, classScore: "20.5", examsScore: 30, totalScore: 999 }, prefs);
    expect(score).toEqual({ subject: "Maths", _id: "5", classScore: 20.5, examsScore: 30, totalScore: 50.5 });
  });

  it("sums without floating point drift and treats a blank part as 0", () => {
    expect(cleanScore({ subject: "A", classScore: 0.1, examsScore: 0.2 }, prefs).score.totalScore).toBe(0.3);
    expect(cleanScore({ subject: "A", classScore: 40, examsScore: "" }, prefs).score.totalScore).toBe(40);
  });

  it("rejects scores outside their share, negative, text, or without a subject", () => {
    expect(cleanScore({ subject: "A", classScore: 51, examsScore: 0 }, prefs).error).toMatch(/Class score/);
    expect(cleanScore({ subject: "A", classScore: 0, examsScore: 51 }, prefs).error).toMatch(/Exams score/);
    expect(cleanScore({ subject: "A", classScore: -1 }, prefs).error).toBeTruthy();
    expect(cleanScore({ subject: "A", classScore: "abc" }, prefs).error).toBeTruthy();
    expect(cleanScore({ classScore: 5 }, prefs).error).toMatch(/subject/);
    expect(cleanScore(null, prefs).error).toBeTruthy();
    expect(cleanScore({ subject: "A" }, prefs, { requireId: true }).error).toMatch(/id/);
  });

  it("drops fields it does not know", () => {
    const { score } = cleanScore({ subject: "A", classScore: 1, examsScore: 1, isAdmin: true, $set: {} }, prefs);
    expect(Object.keys(score).sort()).toEqual(["classScore", "examsScore", "subject", "totalScore"]);
  });

  it("names the failing row when validating a list", () => {
    const { error } = cleanScores([{ subject: "A", classScore: 1 }, { subject: "B", classScore: 99 }], prefs);
    expect(error).toMatch(/^Score 2:/);
    expect(cleanScores("x", prefs).error).toBeTruthy();
  });

  it("merges by key with later entries winning, and totals exactly", () => {
    const merged = mergeBy([{ subject: "A", totalScore: 10 }, { subject: "B", totalScore: 0.1 }], [{ subject: "A", totalScore: 20 }, { subject: "C", totalScore: 0.2 }], "subject");
    expect(merged).toHaveLength(3);
    expect(overallOf(merged)).toBe(20.3);
  });

  it("generates remarks only until someone writes their own", () => {
    const first = nextComments({}, 500);
    expect(first.autoGenerated).toBe(true);
    expect(first.teachersComments).toBeTruthy();
    expect(nextComments(first, 800).autoGenerated).toBe(true); // still automatic: refreshed
    const manual = { teachersComments: "Hand written" };
    expect(nextComments(manual, 800)).toBe(manual);
    expect(nextComments(undefined, 100).autoGenerated).toBe(true);
  });

  it("accepts only plain objects of short values as hand-written comments", () => {
    expect(cleanComments({ conduct: "Good", autoGenerated: true, "a.b": "x", $bad: "y" })).toEqual({ conduct: "Good" });
    for (const bad of ["text", null, [], { a: {} }, { a: [] }]) expect(cleanComments(bad)).toBeNull();
  });
});
