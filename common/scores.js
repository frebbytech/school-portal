const _ = require("lodash");
const { parseMoney, sumAmounts } = require("./money");
const generateRemarks = require("../config/generateRemarks");

/**
 * Exam score rules, kept in one place so every score-writing route applies the same ones.
 *
 * The client sends classScore and examsScore; the total is ALWAYS computed here (it used
 * to be trusted from the request, so a stored total could disagree with its parts).
 */

/** "30/70" -> { class: 30, exams: 70 }; anything unusable falls back to 100/100. */
const scorePreferences = (term) => {
  const [c, e] = String(term?.exams?.scorePreference || "").split("/").map(Number);
  return Number.isFinite(c) && Number.isFinite(e) && c > 0 && e > 0
    ? { class: c, exams: e }
    : { class: 100, exams: 100 };
};

const component = (value, max) => {
  if (value === undefined || value === null || value === "") return 0; // not entered yet
  const n = parseMoney(value, { allowZero: true });
  return n === null || n > max ? null : n;
};

/**
 * Validate one subject score. Returns `{ score }` or `{ error }`. Only known fields are
 * kept; `totalScore` is class + exams. `requireId` is for routes that key scores by the
 * subject id.
 */
const cleanScore = (raw, prefs, { requireId = false } = {}) => {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return { error: "Each score must be an object." };
  if (typeof raw.subject !== "string" || !raw.subject.trim()) return { error: "Each score needs a subject." };
  if (requireId && (raw._id === undefined || raw._id === null || String(raw._id).length > 64)) {
    return { error: "Each score needs the subject id." };
  }

  const classScore = component(raw.classScore, prefs.class);
  const examsScore = component(raw.examsScore, prefs.exams);
  if (classScore === null) return { error: `Class score for ${raw.subject} must be between 0 and ${prefs.class}.` };
  if (examsScore === null) return { error: `Exams score for ${raw.subject} must be between 0 and ${prefs.exams}.` };

  const score = {
    subject: raw.subject.trim().slice(0, 100),
    classScore,
    examsScore,
    totalScore: sumAmounts([classScore, examsScore]),
  };
  if (raw._id !== undefined && raw._id !== null) score._id = String(raw._id);
  for (const key of ["grade", "remarks"]) {
    if (typeof raw[key] === "string") score[key] = raw[key].slice(0, 100);
  }
  return { score };
};

/** Validate a list; returns `{ scores }` or `{ error }` (first problem, with its position). */
const cleanScores = (list, prefs, options) => {
  if (!Array.isArray(list)) return { error: "Scores must be a list." };
  if (list.length > 200) return { error: "Too many scores in one request." };
  const scores = [];
  for (let i = 0; i < list.length; i++) {
    const { score, error } = cleanScore(list[i], prefs, options);
    if (error) return { error: list.length > 1 ? `Score ${i + 1}: ${error}` : error };
    scores.push(score);
  }
  return { scores };
};

/** Later entries replace earlier ones with the same key (the routes' long-standing rule). */
const mergeBy = (existing, incoming, key) =>
  _.values(_.keyBy([...(existing || []), ...incoming], key));

const overallOf = (scores) => sumAmounts(scores, "totalScore");

const isEmptyComments = (comments) =>
  !comments || typeof comments !== "object" || Object.values(comments).every((v) => v === "" || v === undefined || v === null);

/**
 * Remarks are generated automatically only until someone writes their own. Saving
 * scores used to replace hand-written comments with random ones every time.
 */
const nextComments = (current, overall) =>
  isEmptyComments(current) || current.autoGenerated === true
    ? { ...generateRemarks(overall), autoGenerated: true }
    : current;

/** Hand-written comments: a plain object of short text values. Returns null when invalid. */
const cleanComments = (input) => {
  if (!input || typeof input !== "object" || Array.isArray(input)) return null;
  const entries = Object.entries(input);
  if (entries.length > 20) return null;
  const clean = {};
  for (const [key, value] of entries) {
    if (key.startsWith("$") || key.includes(".") || key === "autoGenerated") continue;
    if (value === null || value === undefined) continue;
    if (typeof value !== "string" && typeof value !== "number" && typeof value !== "boolean") return null;
    clean[key] = typeof value === "string" ? value.slice(0, 1000) : value;
  }
  return clean;
};

module.exports = {
  scorePreferences,
  cleanScore,
  cleanScores,
  mergeBy,
  overallOf,
  nextComments,
  cleanComments,
  isEmptyComments,
};
