#!/usr/bin/env node
/**
 * Generates docs/api-reference.md from the route files, so the reference cannot drift
 * from the code. It reads the source text only (no database, no server needed):
 *   node scripts/generate-api-reference.js            # writes docs/api-reference.md
 *   node scripts/generate-api-reference.js --check    # exits 1 if the file is out of date
 */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const appSource = fs.readFileSync(path.join(root, "app.js"), "utf8").replace(/\r\n/g, "\n");

// router variable -> file, then mount path from app.use("/api/...", variable)
const files = {};
for (const m of appSource.matchAll(/const (\w+) = require\("\.\/routes\/(\w+)"\)/g)) files[m[1]] = m[2];
const mounts = [];
let protectedFromHere = false;
for (const line of appSource.split("\n")) {
  if (/app\.use\(verifyJWT\)/.test(line)) protectedFromHere = true;
  const m = line.match(/app\.use\("(\/api\/[^"]+)",\s*(\w+)\)/);
  if (m && files[m[2]]) mounts.push({ prefix: m[1], file: files[m[2]], tokenRequired: protectedFromHere });
}

const GUARD_LABELS = {
  adminOnly: "administrator",
  requireStaff: "staff",
  requireMember: "staff or student",
  requireRoleEnforced: "role-restricted",
  requireRole: "role-restricted",
  staffOrOwnStudent: "staff, or the student themself",
  requireLevelAccess: "class access",
  requireExamAccess: "class access (via record)",
  requireStudentAccess: "student in school",
  requireAttendanceAccess: "class access (via record)",
  verifyJWT: "signed in",
  verifyRefreshJWT: "refresh cookie",
  platformOnly: "platform administrator",
};

const GUARD_NAMES = /\b(platformOnly|verifyRefreshJWT|verifyJWT|adminOnly|requireStaff|requireMember|requireRoleEnforced|requireRole|staffOrOwnStudent|requireLevelAccess|requireExamAccess|requireStudentAccess|requireAttendanceAccess)\b/g;
const HANDLER_START = /asyncHandler\(|async\s*\(|\(req,\s*res|saveRegister\(/;

// Text of the call starting at `open` (index of "("), up to its matching ")".
const callText = (source, open) => {
  let depth = 0;
  let quote = null;
  for (let i = open; i < source.length; i++) {
    const c = source[i];
    if (quote) {
      if (c === "\\") i++;
      else if (c === quote) quote = null;
    } else if (c === '"' || c === "'" || c === "`") quote = c;
    else if (c === "(") depth++;
    else if (c === ")" && --depth === 0) return source.slice(open, i + 1);
  }
  return source.slice(open);
};

const labelFor = (text) => {
  const guards = [...new Set(text.match(GUARD_NAMES) || [])];
  return guards
    .map((g) => (g === "requireRole" || g === "requireRoleEnforced") && /platform_admin/.test(text) ? "platform administrator" : GUARD_LABELS[g])
    .filter((v, i, all) => all.indexOf(v) === i);
};

const rows = [];
for (const { prefix, file, tokenRequired } of mounts) {
  const source = fs.readFileSync(path.join(root, "routes", `${file}.js`), "utf8").replace(/\r\n/g, "\n");

  // Guards applied to the whole router with router.use(...)
  const routerWide = [];
  for (const m of source.matchAll(/router\.use\(/g)) routerWide.push(...labelFor(callText(source, m.index + "router.use".length)));

  for (const m of source.matchAll(/router\.(get|post|put|patch|delete)\(/g)) {
    const call = callText(source, m.index + m[0].length - 1);
    const pathMatch = call.match(/^\(\s*(["'`])([^"'`]*)\1/);
    if (!pathMatch) continue;
    const head = call.split(HANDLER_START)[0];
    let labels = [...new Set([...routerWide, ...labelFor(head)])];
    if (labels.length > 1) labels = labels.filter((l) => l !== "signed in");
    const access = labels.length ? labels.join(" + ") : tokenRequired ? "signed in (checks inside)" : "public";
    rows.push({ group: file.replace(/Route$/, ""), method: m[1].toUpperCase(), path: prefix + (pathMatch[2] === "/" ? "" : pathMatch[2]), access });
  }
}

const order = ["GET", "POST", "PUT", "PATCH", "DELETE"];
rows.sort((a, b) => a.group.localeCompare(b.group) || a.path.localeCompare(b.path) || order.indexOf(a.method) - order.indexOf(b.method));

let out = `# API reference

Generated by \`node scripts/generate-api-reference.js\` from the route files: do not edit by hand.
Base URL: \`/api/frebbys/v1\`. Everything below needs a signed-in user (Bearer access token) unless it says **public** (no bearer token: login, token refresh and password-reset flows, which use credentials, cookies or one-time codes instead).
"Access" lists the guards declared on the route; ownership and school scoping are applied inside the handlers (see \`docs/refactoring-progress.md\` §5). When the \`ENFORCE_AUTHZ\` switch is off, role guards are skipped; the platform and school-scoping rules always apply.

Common behaviour:
- Errors: \`{status, statusCode, message}\` plus \`code\` and \`requestId\`, or a bare string on older routes (see \`docs/legacy-quirks.md\`).
- Lists accept optional \`?page=&limit=\` (limit max 200). Without them the full array is returned as before; with them the total is in the \`X-Total-Count\` header.
- Every response carries \`X-Request-Id\`.

`;
let group = null;
for (const r of rows) {
  if (r.group !== group) {
    group = r.group;
    out += `\n## ${group}\n\n| Method | Path | Access |\n|---|---|---|\n`;
  }
  out += `| ${r.method} | \`${r.path}\` | ${r.access} |\n`;
}
out += `\n_${rows.length} endpoints._\n`;

const target = path.join(root, "docs", "api-reference.md");
if (process.argv.includes("--check")) {
  // Ignore line endings: a Windows checkout may convert the file to CRLF.
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== out) {
    console.error("docs/api-reference.md is out of date; run node scripts/generate-api-reference.js");
    process.exit(1);
  }
  console.log("api reference up to date");
} else {
  fs.writeFileSync(target, out);
  console.log(`wrote docs/api-reference.md (${rows.length} endpoints)`);
}
